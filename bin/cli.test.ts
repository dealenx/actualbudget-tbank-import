describe('parseTbankCsv', () => {
  it('parses credit transaction', () => {
    const rows = parseTbankCsv(sampleCsv);
    expect(rows[0]).toMatchObject({
      date: '2026-01-08',
      amount: 10500.0,
      payee: 'ГОРОДИЛОВ ДАНИИЛ ВЛАДИМИРОВИЧ',
      notes: 'Перевод с карты *0271',
      importedId: '862268',
    });
  });

  it('parses debit transaction with negative amount', () => {
    const rows = parseTbankCsv(sampleCsv);
    expect(rows[1]).toMatchObject({
      date: '2026-01-08',
      amount: -490.0,
      payee: 'АО "ТБанк"',
      importedId: '127353',
    });
  });

  it('normalizes payee abbreviations', () => {
    const rows = parseTbankCsv(sampleCsv);
    expect(rows[1].payee).toBe('АО "ТБанк"');
    expect(rows[2].payee).toBe('ООО "ЦИФРОВЫЕ ОБРАЗОВАТЕЛЬНЫЕ РЕШЕНИЯ"');
  });

  it('returns empty array for empty input', () => {
    expect(parseTbankCsv('')).toEqual([]);
  });

  it('returns empty array for header-only input', () => {
    expect(parseTbankCsv('header;line')).toEqual([]);
  });
});

describe('convertToActualCsv', () => {
  it('produces valid CSV with header', () => {
    const rows = parseTbankCsv(sampleCsv);
    const csv = convertToActualCsv(rows);
    const lines = csv.split('\n');
    expect(lines[0]).toBe('Date,Payee,Notes,Amount,ImportedID');
    expect(lines.length).toBe(4);
  });

  it('formats amount with two decimals', () => {
    const rows = parseTbankCsv(sampleCsv);
    const csv = convertToActualCsv(rows);
    expect(csv).toContain(',10500.00,');
    expect(csv).toContain(',-490.00,');
    expect(csv).toContain(',2645.13,');
  });
});
